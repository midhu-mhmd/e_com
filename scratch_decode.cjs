const cp1252 = {
  0x22: 0x22,
  0x178: 0x9f,
  0xaf: 0xaf,
  0x17d: 0x8e,
  0xc4: 0xc4,
  0xdf: 0xdf,
  0x2022: 0x95,
  0xe2: 0xe2,
  0xf3: 0xf3,
  0xae: 0xae,
  0x2018: 0x91,
  0xf2: 0xf2,
  0xb3: 0xb3
};

const hexList = [
  // word 1:
  [0x22], // wait, could " be 0x22 or something?
  [0x9f, 0xaf, 0x8e, 0xc4, 0xdf, 0x95],
  // space
  // word 2:
  [0xe2, 0xf3, 0xae, 0x91],
  // space
  // word 3:
  [0xf2, 0xb3]
];

for (const group of hexList) {
  const chars = group.map(h => String.fromCharCode(0xfe00 + h));
  console.log(chars.join(''), group.map(h => 'FE' + h.toString(16).toUpperCase()).join(' '));
}

// Let's also see what Arabic letters these presentation forms correspond to:
const charsAll = [0x9f, 0xaf, 0x8e, 0xc4, 0xdf, 0x95, 0x20, 0xe2, 0xf3, 0xae, 0x91, 0x20, 0xf2, 0xb3];
const str = charsAll.map(h => h === 0x20 ? ' ' : String.fromCharCode(0xfe00 + h)).join('');
console.log('Presentation form string:', str);
console.log('Normalized (NFKC):', str.normalize('NFKD'), str.normalize('NFKC'));
